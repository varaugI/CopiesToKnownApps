export function getUser(userId: string) {
  return users.find((user) => user.id === userId) ?? users[0]!;
}

export function getUserByHandle(handle: string) {
  return users.find((user) => user.handle.toLowerCase() === handle.toLowerCase());
}

export function getTweet(tweetId: string) {
  return [...tweets, ...replyTweets].find((tweet) => tweet.id === tweetId);
}
